#!/usr/bin/env python3
"""Conductor codemap: an incremental, deterministic project map.

Goal: never re-scan the whole project with a model. A script keeps a file graph
(hashes, module membership, dependency edges) up to date; the model reads only
MAP.md (compact index) and the module cards it actually needs.

Layout under <project>/.conductor/:
  map.json          machine graph (files, deps, modules, stale flags)
  MAP.md            compact human/model index, regenerated by this script
  cards/<mod>.md    module cards written by the cartographer agent (model-written)

Commands:
  ensure                    init if needed, else sync; print MAP (entry point for any chat)
  init                      full scan (no model involved), creates card stubs
  sync                      cheap incremental pass (mtime/size), used at SessionStart
  update FILE...            re-index given files
  impact FILE...            print direct dependents + affected modules
  stale                     list modules whose cards need refresh
  fresh MODULE...           mark module cards as refreshed
  render                    rebuild MAP.md
  hook-post-edit            PostToolUse hook (reads stdin JSON)
  hook-session-start        SessionStart hook (reads stdin JSON)
"""
import fnmatch
import hashlib
import os
import re
import sys
import time
from pathlib import Path, PurePosixPath

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _common import (emit_context, load_config, project_dir, read_hook_input,  # noqa: E402
                     read_json, state_dir, write_json)

IGNORE_DIRS = {".git", ".hg", ".svn", "node_modules", ".conductor", "__pycache__", ".venv",
               "venv", "env", "dist", "build", "out", "target", ".next", ".nuxt", ".cache",
               "Library", "Temp", "Logs", "obj", "bin", ".godot", ".import", ".idea",
               ".vscode", ".pytest_cache", ".mypy_cache", "coverage", ".gradle"}
TEXT_EXT = {".py", ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".vue", ".svelte", ".gd",
            ".cs", ".go", ".rs", ".java", ".kt", ".swift", ".c", ".h", ".cpp", ".hpp",
            ".lua", ".rb", ".php", ".sql", ".md", ".txt", ".html", ".htm", ".css", ".scss",
            ".json", ".yaml", ".yml", ".toml", ".ini", ".cfg", ".tscn", ".tres", ".shader",
            ".gdshader", ".ipynb", ".r", ".R", ".csv", ".sh", ".ps1", ".bat", ".xml"}
GROUP_ROOTS = {"src", "lib", "app", "apps", "packages", "Assets", "Scripts", "scripts",
               "modules", "services", "internal", "pkg", "docs", "notebooks"}
SOURCE_EXT_ORDER = [".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue", ".svelte", ".py",
                    ".gd", ".md"]

STDLIB = set(getattr(sys, "stdlib_module_names", ())) | {"__future__"}
RE_ANNOT = re.compile(r"@map:\s*(depends|tags)\s*=\s*([^\n*]+)")
RE_PY = re.compile(r"^\s*(?:from\s+(\.*[\w.]*)\s+import\s+([\w*, ()]+)|import\s+([\w., ]+))", re.M)
RE_JS = re.compile(r"""(?:import\s[^'"]*?from\s*|import\s*\(\s*|require\s*\(\s*|export\s[^'"]*?from\s*|import\s+)['"]([^'"]+)['"]""")
RE_GD = re.compile(r"""(?:preload|load|extends)\s*\(?\s*["']res://([^"']+)["']""")
RE_TSCN = re.compile(r"""path="res://([^"]+)\"""")
RE_MDLINK = re.compile(r"\[[^\]]*\]\(([^)\s#]+)(?:#[^)]*)?\)")
RE_WIKI = re.compile(r"\[\[([^\]|#]+)")
RE_HTML = re.compile(r"""(?:src|href)\s*=\s*["']([^"'#?]+)""")


# ---------------------------------------------------------------- helpers
def rel(root, p):
    return PurePosixPath(Path(p).resolve().relative_to(Path(root).resolve())).as_posix()


def sha(path):
    h = hashlib.sha1()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()[:12]


def module_of(relpath, cfg):
    for mod, globs in (cfg["codemap"].get("modules") or {}).items():
        for g in globs:
            if fnmatch.fnmatch(relpath, g):
                return mod
    parts = relpath.split("/")
    if len(parts) == 1:
        return "_root"
    if parts[0] in GROUP_ROOTS and len(parts) > 2:
        return parts[0] + "/" + parts[1]
    return parts[0]


def ignored(relpath, cfg):
    for g in cfg["codemap"].get("ignore") or []:
        if fnmatch.fnmatch(relpath, g):
            return True
    return False


WALK_STATE = {"truncated": False}


def walk(root, cfg):
    root = Path(root)
    limit = cfg["codemap"]["max_files"]
    maxb = cfg["codemap"]["max_file_bytes"]
    n = 0
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in IGNORE_DIRS and not d.startswith(".")
                             or d in (".github", ".claude"))
        dirnames[:] = [d for d in dirnames if d not in IGNORE_DIRS]
        for fn in sorted(filenames):
            p = Path(dirpath) / fn
            if p.suffix not in TEXT_EXT and fn not in ("Dockerfile", "Makefile", "CLAUDE.md"):
                continue
            try:
                st = p.stat()
            except OSError:
                continue
            if st.st_size > maxb:
                continue
            r = rel(root, p)
            if ignored(r, cfg):
                continue
            n += 1
            if n > limit:
                WALK_STATE["truncated"] = True
                return
            yield r, st


def godot_root(root):
    root = Path(root)
    if (root / "project.godot").exists():
        return root
    for p in root.glob("*/project.godot"):
        return p.parent
    return root


def resolve_candidates(root, base_rel, spec, known):
    """Resolve an import spec to a known project file (posix rel path) or None."""
    base_dir = PurePosixPath(base_rel).parent
    cands = []
    if spec.startswith("."):
        target = (base_dir / spec).as_posix()
    elif spec.startswith("/"):
        target = spec.lstrip("/")
    else:
        target = spec
    target = os.path.normpath(target).replace("\\", "/")
    if target.startswith(".."):
        return None
    cands.append(target)
    for ext in SOURCE_EXT_ORDER:
        cands.append(target + ext)
        cands.append(target + "/index" + ext)
    cands.append(target + "/__init__.py")
    for c in cands:
        if c in known:
            return c
    return None


def extract_deps(root, relpath, text, known, groot_rel):
    deps, ext, tags = set(), set(), set()
    suf = PurePosixPath(relpath).suffix

    for kind, val in RE_ANNOT.findall(text):
        items = [x.strip() for x in val.split(",") if x.strip()]
        if kind == "depends":
            for it in items:
                r = resolve_candidates(root, "", it, known) or resolve_candidates(root, relpath, it, known)
                (deps if r else ext).add(r or it)
        else:
            tags.update(items)

    def add(spec, relative_to=relpath):
        r = resolve_candidates(root, relative_to, spec, known)
        if r and r != relpath:
            deps.add(r)
        elif not r and spec.startswith("."):
            ext.add(spec)

    if suf == ".py":
        for frm, names, imp in RE_PY.findall(text):
            if frm:
                if frm.startswith("."):
                    dots = len(frm) - len(frm.lstrip("."))
                    mod = frm.lstrip(".").replace(".", "/")
                    base = PurePosixPath(relpath).parent
                    for _ in range(dots - 1):
                        base = base.parent
                    spec = (base / mod).as_posix() if mod else base.as_posix()
                    r = resolve_candidates(root, "", spec, known)
                    if not r and not mod:  # from . import a, b
                        for nm in re.findall(r"\w+", names):
                            cand = (base / nm).as_posix()
                            r2 = resolve_candidates(root, "", cand, known)
                            if r2:
                                deps.add(r2)
                            else:
                                ext.add(cand)
                    elif r:
                        deps.add(r)
                    else:
                        ext.add(spec)
                else:
                    spec = frm.replace(".", "/")
                    sub = []
                    for nm in re.findall(r"\w+", names):
                        for pre in ("", "src/"):
                            r2 = resolve_candidates(root, "", pre + spec + "/" + nm, known)
                            if r2:
                                sub.append(r2)
                                break
                    if sub:
                        deps.update(sub)
                    else:
                        r = resolve_candidates(root, "", spec, known) or resolve_candidates(
                            root, "", "src/" + spec, known)
                        if r:
                            deps.add(r)
                        elif frm.split(".")[0] not in STDLIB:
                            ext.add(frm)
            else:
                for m in imp.split(","):
                    m = m.strip().split(" ")[0]
                    if not m:
                        continue
                    r = resolve_candidates(root, "", m.replace(".", "/"), known)
                    if r:
                        deps.add(r)
                    elif m.split(".")[0] not in STDLIB:
                        ext.add(m)
    elif suf in (".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".vue", ".svelte"):
        for spec in RE_JS.findall(text):
            if spec.startswith(".") or spec.startswith("/"):
                add(spec)
            elif spec.startswith("@/") or spec.startswith("~/"):
                r = resolve_candidates(root, "", "src/" + spec[2:], known)
                if r:
                    deps.add(r)
                else:
                    ext.add(spec)
    elif suf in (".gd", ".tscn", ".tres"):
        rx = RE_GD if suf == ".gd" else RE_TSCN
        for spec in rx.findall(text):
            r = resolve_candidates(root, "", (PurePosixPath(groot_rel) / spec).as_posix()
                                   if groot_rel not in ("", ".") else spec, known)
            if r and r != relpath:
                deps.add(r)
            elif not r:
                ext.add("res://" + spec)
    elif suf == ".md":
        for spec in RE_MDLINK.findall(text):
            if "://" in spec or spec.startswith("mailto:"):
                continue
            add(spec if spec.startswith((".", "/")) else "./" + spec)
        for name in RE_WIKI.findall(text):
            tags.add("link:" + name.strip())
    elif suf in (".html", ".htm"):
        for spec in RE_HTML.findall(text):
            if "://" in spec or spec.startswith(("data:", "mailto:", "javascript:")):
                continue
            add(spec if spec.startswith((".", "/")) else "./" + spec)
    return sorted(deps), sorted(ext)[:50], sorted(tags)


def read_text(root, relpath):
    try:
        return (Path(root) / relpath).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


# ---------------------------------------------------------------- map ops
def map_path(root):
    return state_dir(root) / "map.json"


def load_map(root):
    return read_json(map_path(root), None)


def empty_map():
    return {"version": 1, "updated": 0, "files": {}, "modules": {}}


def index_file(root, m, relpath, st, known, groot_rel, cfg):
    text = read_text(root, relpath)
    h = hashlib.sha1(text.encode("utf-8", "replace")).hexdigest()[:12]
    deps, ext, tags = extract_deps(root, relpath, text, known, groot_rel)
    prev = m["files"].get(relpath)
    mod = module_of(relpath, cfg)
    changed = (prev is None) or prev.get("h") != h
    m["files"][relpath] = {"h": h, "m": mod, "d": deps, "x": ext, "t": tags,
                           "mt": int(st.st_mtime), "sz": st.st_size,
                           "lines": text.count("\n") + 1}
    return changed, mod


def rebuild_modules(m, root):
    mods = {}
    cards_dir = state_dir(root) / "cards"
    for f, info in m["files"].items():
        mm = mods.setdefault(info["m"], {"files": 0, "lines": 0, "deps": set()})
        mm["files"] += 1
        mm["lines"] += info.get("lines", 0)
        for d in info["d"]:
            dm = m["files"].get(d, {}).get("m")
            if dm and dm != info["m"]:
                mm["deps"].add(dm)
    old = m.get("modules", {})
    out = {}
    for k, v in mods.items():
        prev = old.get(k, {})
        card = cards_dir / (k.replace("/", "__") + ".md")
        out[k] = {"files": v["files"], "lines": v["lines"], "deps": sorted(v["deps"]),
                  "stale": prev.get("stale", True), "card": card.relative_to(root).as_posix(),
                  "purpose": card_purpose(card)}
    m["modules"] = out


def card_purpose(card):
    try:
        for line in card.read_text(encoding="utf-8").splitlines():
            if line.lower().startswith("purpose:"):
                return line.split(":", 1)[1].strip()[:120]
    except OSError:
        pass
    return ""


def mark_stale(m, mods):
    for mod in mods:
        if mod in m["modules"]:
            m["modules"][mod]["stale"] = True


def render(root, m, cfg):
    lines = ["# Project map (generated by conductor codemap; do not edit by hand)",
             "",
             "Read a module card only when the task touches that module. "
             "Edited files report their dependents automatically.",
             "",
             "| module | files | lines | depends on | card | purpose |",
             "|---|---|---|---|---|---|"]
    for k in sorted(m["modules"]):
        v = m["modules"][k]
        status = "STALE" if v["stale"] else "ok"
        lines.append("| {} | {} | {} | {} | {} | {} |".format(
            k, v["files"], v["lines"], ", ".join(v["deps"][:6]) or "-", status,
            v.get("purpose") or "-"))
    lines += ["", "Updated: " + time.strftime("%Y-%m-%d %H:%M", time.localtime(m["updated"]))]
    p = state_dir(root) / "MAP.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return "\n".join(lines)


def card_stub(root, mod, info, m):
    p = Path(root) / info["card"]
    if p.exists():
        return
    p.parent.mkdir(parents=True, exist_ok=True)
    files = sorted(f for f, i in m["files"].items() if i["m"] == mod)
    p.write_text(
        "# Module: {}\n\npurpose: (to be written by cartographer)\n\n"
        "## Entry points / public interface\n- TODO\n\n## Invariants & decisions\n- TODO\n\n"
        "## Files ({})\n{}\n".format(mod, len(files), "\n".join("- " + f for f in files[:60])),
        encoding="utf-8")


def full_scan(root, cfg):
    m = load_map(root) or empty_map()
    entries = list(walk(root, cfg))
    known = {r for r, _ in entries}
    groot_rel = rel(root, godot_root(root)) if godot_root(root) != Path(root) else ""
    seen = set()
    changed_mods = set()
    for r, st in entries:
        seen.add(r)
        changed, mod = index_file(root, m, r, st, known, groot_rel, cfg)
        if changed:
            changed_mods.add(mod)
    for r in list(m["files"]):
        if r not in seen:
            changed_mods.add(m["files"][r]["m"])
            del m["files"][r]
    m["updated"] = int(time.time())
    rebuild_modules(m, root)
    mark_stale(m, changed_mods)
    return m, changed_mods


def sync(root, cfg):
    """Incremental: only files whose mtime/size changed, plus additions/removals."""
    m = load_map(root)
    if m is None:
        return None, set()
    entries = list(walk(root, cfg))
    known = {r for r, _ in entries}
    groot_rel = rel(root, godot_root(root)) if godot_root(root) != Path(root) else ""
    changed_mods = set()
    seen = set()
    structure_changed = False
    for r, st in entries:
        seen.add(r)
        prev = m["files"].get(r)
        if prev and prev.get("mt") == int(st.st_mtime) and prev.get("sz") == st.st_size:
            continue
        if prev is None:
            structure_changed = True
        changed, mod = index_file(root, m, r, st, known, groot_rel, cfg)
        if changed:
            changed_mods.add(mod)
    for r in list(m["files"]):
        if r not in seen:
            structure_changed = True
            changed_mods.add(m["files"][r]["m"])
            del m["files"][r]
    if structure_changed:  # new files may resolve previously-unresolved imports
        changed_mods.update(reresolve(root, m, known, groot_rel, cfg).values())
    if changed_mods or structure_changed:
        m["updated"] = int(time.time())
        rebuild_modules(m, root)
        mark_stale(m, changed_mods)
    return m, changed_mods


def _stems(files):
    out = set()
    for f in files:
        pp = PurePosixPath(f)
        out.add(pp.stem)
        if pp.stem in ("__init__", "index", "mod"):
            out.add(pp.parent.name)
    return out


def reresolve(root, m, known, groot_rel, cfg, exclude=(), new_files=None):
    """Re-index files that had unresolved imports or links to removed files.

    Called whenever files appear or disappear, so an import written before its target
    existed is linked as soon as the target is created. Returns {file: module} for
    files whose dependency list changed."""
    rewired = {}
    stems = _stems(new_files) if new_files is not None else None
    for r, info in list(m["files"].items()):
        if r in exclude:
            continue
        missing = any(d not in known for d in info["d"])
        if not missing:
            if not info.get("x"):
                continue
            if stems is not None and not any(re.split(r"[/.]", x.rstrip("/"))[-1] in stems
                                             for x in info["x"]):
                continue
        try:
            st = os.stat(Path(root) / r)
        except OSError:
            continue
        before = list(info["d"])
        index_file(root, m, r, st, known, groot_rel, cfg)
        if m["files"][r]["d"] != before:
            rewired[r] = m["files"][r]["m"]
    return rewired


def update_files(root, cfg, files):
    m = load_map(root)
    if m is None:
        return None, set(), [], [], []
    known = set(m["files"])
    groot_rel = rel(root, godot_root(root)) if godot_root(root) != Path(root) else ""
    changed_mods, touched, changed_files = set(), [], []
    structure_changed = False
    new_files = []
    for f in files:
        p = Path(f)
        if not p.is_absolute():
            p = Path(root) / p
        try:
            r = rel(root, p)
        except ValueError:
            continue  # outside project
        if r.startswith(".conductor/") or ignored(r, cfg):
            continue
        if any(part in IGNORE_DIRS for part in r.split("/")[:-1]):
            continue
        if not p.exists():
            if r in m["files"]:
                changed_mods.add(m["files"][r]["m"])
                del m["files"][r]
                touched.append(r)
                changed_files.append(r)
                known.discard(r)
                structure_changed = True
            continue
        if p.suffix not in TEXT_EXT:
            continue
        if r not in m["files"]:
            structure_changed = True
            new_files.append(r)
        known.add(r)
        changed, mod = index_file(root, m, r, p.stat(), known, groot_rel, cfg)
        touched.append(r)
        if changed:
            changed_mods.add(mod)
            changed_files.append(r)
    rewired = {}
    if structure_changed:
        rewired = reresolve(root, m, known, groot_rel, cfg, exclude=set(touched), new_files=new_files)
        changed_mods.update(rewired.values())
    if touched:
        m["updated"] = int(time.time())
        rebuild_modules(m, root)
        mark_stale(m, changed_mods)
    return m, changed_mods, touched, changed_files, sorted(rewired)


def dependents(m, targets):
    tset = set(targets)
    return sorted(f for f, i in m["files"].items() if tset.intersection(i["d"]) and f not in tset)


def save(root, m, cfg):
    write_json(map_path(root), m)
    render(root, m, cfg)


# ---------------------------------------------------------------- commands
def unsafe_root(root):
    r = Path(root).resolve()
    home = Path.home().resolve()
    return r == home or r == Path(r.anchor) or r in (home / "Desktop", home / "Documents", home / "Downloads")


def write_local_gitignore(root):
    p = state_dir(root) / ".gitignore"
    if not p.exists():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("# Conductor: keep map, cards and config in git; skip bulky run data\n"
                     "usage/\nruns/*/evidence/\nruns/*/analysis/*.out\n", encoding="utf-8")


def cmd_init(root, cfg, quiet=False):
    m, _ = full_scan(root, cfg)
    save(root, m, cfg)
    for mod, info in m["modules"].items():
        card_stub(root, mod, info, m)
    cp = state_dir(root) / "config.json"
    if not cp.exists():
        write_json(cp, {"profile": cfg["profile"]})
    write_local_gitignore(root)
    if not quiet:
        print("codemap: {} files, {} modules -> {}".format(
            len(m["files"]), len(m["modules"]), (state_dir(root) / "MAP.md").as_posix()))
    return m


def cmd_ensure(root, cfg):
    """One-step entry used by /conductor:conduct in any project and any chat.

    Not initialised -> fast script-only init (no model, no cards written by agents).
    Initialised     -> cheap incremental sync.
    Then prints the compact map so it lands in the current conversation's context,
    which makes a session that started before installation (or before init) work too."""
    if unsafe_root(root):
        print("conductor: refusing to index {} (home/system folder). Open a project folder and "
              "run the command there.".format(root))
        return 3
    if not map_path(root).exists():
        m = cmd_init(root, cfg, quiet=True)
        head = "conductor: project initialised now ({} files, {} modules; cards are filled lazily " \
               "for modules a task touches).".format(len(m["files"]), len(m["modules"]))
    else:
        m, ch = sync(root, cfg)
        save(root, m, cfg)
        head = "conductor: map synced ({} files; changed modules: {}).".format(
            len(m["files"]), ", ".join(sorted(ch)) or "none")
    if WALK_STATE["truncated"]:
        head += " WARNING: file limit codemap.max_files reached; map is partial — set " \
                "codemap.ignore/modules in .conductor/config.json."
    print(head)
    text = (state_dir(root) / "MAP.md").read_text(encoding="utf-8")
    limit = cfg["codemap"]["session_map_chars"]
    print(text if len(text) <= limit else text[:limit] + "\n...(truncated; read .conductor/MAP.md)")
    return 0


def cmd_hook_post_edit(root, cfg):
    data = read_hook_input()
    ti = data.get("tool_input") or {}
    paths = []
    for key in ("file_path", "notebook_path", "path"):
        if ti.get(key):
            paths.append(ti[key])
    for e in ti.get("edits") or []:
        if isinstance(e, dict) and e.get("file_path"):
            paths.append(e["file_path"])
    if not paths or not map_path(root).exists():
        return
    m, changed_mods, touched, changed_files, rewired = update_files(root, cfg, paths)
    if not m or not touched:
        return
    save(root, m, cfg)
    if not changed_files and not rewired:
        return
    deps = dependents(m, changed_files)
    msg = "codemap: indexed {}.".format(", ".join(changed_files[:5]) or ", ".join(touched[:5]))
    if rewired:
        msg += " Newly linked importers (their imports now resolve): {}.".format(", ".join(rewired[:12]))
    if deps:
        msg += " Direct dependents to re-check: {}{}.".format(
            ", ".join(deps[:12]), " (+{} more)".format(len(deps) - 12) if len(deps) > 12 else "")
    if changed_mods:
        msg += " Module card(s) now stale: {}.".format(", ".join(sorted(changed_mods)))
    emit_context("PostToolUse", msg)


def cmd_hook_session_start(root, cfg):
    read_hook_input()
    sd = state_dir(root)
    if not sd.exists():
        return
    m, _ = sync(root, cfg)
    if m is not None:
        save(root, m, cfg)
    parts = ["This project uses the Conductor plugin (.conductor/). For non-trivial tasks follow "
             "the conductor:conduct protocol: forge a spec, delegate routine work to cheap "
             "subagents, verify before delivering. Navigate with the map below first and open module cards "
             "(.conductor/cards/) only for modules the task touches; widen to a targeted search only "
             "when the map cannot answer, instead of reading the whole repo."]
    mp = sd / "MAP.md"
    if mp.exists():
        text = mp.read_text(encoding="utf-8")
        limit = cfg["codemap"]["session_map_chars"]
        if len(text) > limit:
            text = text[:limit] + "\n...(truncated; read .conductor/MAP.md for the rest)"
        parts.append(text)
    emit_context("SessionStart", "\n\n".join(parts))


def main(argv):
    if not argv:
        print(__doc__)
        return 0
    cmd, args = argv[0], argv[1:]
    hook_cmds = ("hook-post-edit", "hook-session-start")
    root = project_dir()
    cfg = load_config(root)
    try:
        if cmd == "init":
            cmd_init(root, cfg)
        elif cmd == "ensure":
            return cmd_ensure(root, cfg)
        elif cmd == "sync":
            m, ch = sync(root, cfg)
            if m is None:
                print("codemap: not initialised; run init")
                return 1
            save(root, m, cfg)
            print("codemap: synced; changed modules: {}".format(", ".join(sorted(ch)) or "none"))
        elif cmd == "update":
            m, ch, touched, _, _ = update_files(root, cfg, args)
            if m is None:
                print("codemap: not initialised; run init")
                return 1
            save(root, m, cfg)
            print("codemap: updated {}; stale: {}".format(len(touched), ", ".join(sorted(ch)) or "none"))
        elif cmd == "impact":
            m = load_map(root) or empty_map()
            targets = []
            for a in args:
                p = Path(a)
                targets.append(rel(root, p if p.is_absolute() else Path(root) / p))
            deps = dependents(m, targets)
            mods = sorted({m["files"][d]["m"] for d in deps} |
                          {m["files"].get(t, {}).get("m") for t in targets if t in m["files"]})
            print("dependents:\n" + ("\n".join("  " + d for d in deps) or "  (none)"))
            print("modules: " + ", ".join(mods))
        elif cmd == "stale":
            m = load_map(root) or empty_map()
            for k, v in sorted(m["modules"].items()):
                if v["stale"]:
                    print("{}\t{}".format(k, v["card"]))
        elif cmd == "fresh":
            m = load_map(root) or empty_map()
            for a in args:
                if a in m["modules"]:
                    m["modules"][a]["stale"] = False
                    m["modules"][a]["purpose"] = card_purpose(Path(root) / m["modules"][a]["card"])
            save(root, m, cfg)
            print("codemap: marked fresh: " + ", ".join(args))
        elif cmd == "render":
            m = load_map(root) or empty_map()
            rebuild_modules(m, root)
            print(render(root, m, cfg))
        elif cmd == "hook-post-edit":
            cmd_hook_post_edit(root, cfg)
        elif cmd == "hook-session-start":
            cmd_hook_session_start(root, cfg)
        else:
            print("unknown command: " + cmd)
            return 2
    except Exception as e:  # hooks must never break the session
        if cmd in hook_cmds:
            sys.stderr.write("codemap hook error: {}\n".format(e))
            return 0
        raise
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
